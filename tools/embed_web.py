"""Gzip everything in web/ into src/web_assets.c.

Runs automatically as a PlatformIO pre-build script, and can also be run by
hand:  python tools/embed_web.py
"""

import gzip
import os

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".png": "image/png",
    ".json": "application/json",
}


def generate(project_dir):
    web_dir = os.path.join(project_dir, "web")
    out_path = os.path.join(project_dir, "src", "web_assets.c")

    names = sorted(n for n in os.listdir(web_dir) if os.path.splitext(n)[1] in MIME)
    lines = [
        "/* Generated by tools/embed_web.py from web/ - do not edit. */",
        '#include "web_assets.h"',
        "",
    ]
    table = []
    total = 0
    for i, name in enumerate(names):
        with open(os.path.join(web_dir, name), "rb") as fp:
            raw = fp.read()
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(packed)
        lines.append("static const uint8_t asset_%d[] = {" % i)
        for off in range(0, len(packed), 20):
            lines.append("    " + ",".join("0x%02x" % b for b in packed[off:off + 20]) + ",")
        lines.append("};")
        lines.append("")
        table.append('    {"/%s", "%s", asset_%d, sizeof(asset_%d)},'
                     % (name, MIME[os.path.splitext(name)[1]], i, i))
    lines.append("const web_asset_t web_assets[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append("const size_t web_assets_count = sizeof(web_assets) / sizeof(web_assets[0]);")
    content = "\n".join(lines) + "\n"

    old = None
    if os.path.exists(out_path):
        with open(out_path, "r", encoding="utf-8") as fp:
            old = fp.read()
    if old != content:
        with open(out_path, "w", encoding="utf-8", newline="\n") as fp:
            fp.write(content)
    print("embed_web: %d files, %d bytes gzipped -> %s" % (len(names), total, out_path))


try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    generate(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
